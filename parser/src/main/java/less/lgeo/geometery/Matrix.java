package less.lgeo.geometery;

public class Matrix {
    private final int x;
    private final int y;
    private final int z;
    private final int a;
    private final int b;
    private final int c;
    private final int d;
    private final int e;
    private final int f;
    private final int g;
    private final int h;
    private final int i;

    public Matrix( int x, int y, int z, int a, int b, int c, int d, int e, int f, int g, int h, int i ) {
        this.x = x;
        this.y = y;
        this.z = z;
        this.a = a;
        this.b = b;
        this.c = c;
        this.d = d;
        this.e = e;
        this.f = f;
        this.g = g;
        this.h = h;
        this.i = i;
    }
}
